"""Record source-overlap candidates for human provenance review (not a legal verdict).

Uses local Git repositories only. Scans tracked C/C++/Python/INI files, current
and reachable historical EasyREAD/freeink-reader blobs, plus current SDK and
converter sources. Generated byte/data headers and vendored third_party code
are reviewed separately in the accompanying human report, not treated as
application authorship by this search.
"""
