import argparse
import bisect
import hashlib
import json
import re
import subprocess
from collections import defaultdict
from pathlib import Path

EXTENSIONS = {'.h', '.hpp', '.c', '.cpp', '.py', '.ini'}
GENERATED = {'GbkTable.h', 'ui_font.h', 'splash.h', 'icons_gen.h'}
LEX = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|\#[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|[A-Za-z_]\w*|0[xX][0-9a-fA-F]+|\d+(?:\.\d+)?|[^\s]')
WORDS = set('if else for while return class struct public private protected virtual override const static constexpr inline namespace using void bool int unsigned long float double auto sizeof nullptr true false switch case break continue new delete template typename include pragma define'.split())

def git(root, *args):
    return subprocess.check_output(['git', '-C', str(root), *args])

def eligible(path):
    p = Path(path)
    return p.suffix in EXTENSIONS and p.name not in GENERATED and 'third_party' not in p.parts

def collect(root, family, history):
    records = {}
    commits = git(root, 'rev-list', '--all').decode().splitlines() if history else [git(root, 'rev-parse', 'HEAD').decode().strip()]
    for commit in commits:
        for row in git(root, 'ls-tree', '-r', commit).decode().splitlines():
            meta, path = row.split('\t', 1)
            _, kind, blob = meta.split()
            if kind != 'blob' or not eligible(path) or (blob, path) in records:
                continue
            data = git(root, 'cat-file', 'blob', blob)
            if len(data) > 300000:
                continue
            records[blob, path] = {'family': family, 'path': path, 'git_blob': blob,
                'commit': commit,
                'sha256': hashlib.sha256(data).hexdigest(), 'text': data.decode('utf-8', errors='replace')}
    return list(records.values())

def tokenize(record, abstract):
    text = record['text']
    newlines = [m.start() for m in re.finditer('\n', text)]
    values, lines = [], []
    for match in LEX.finditer(text):
        value = match.group()
        if value.startswith(('//', '/*', '#')):
            continue
        if abstract and re.fullmatch(r'[A-Za-z_]\w*', value) and value not in WORDS:
            value = 'IDENT'
        values.append(value)
        lines.append(bisect.bisect_left(newlines, match.start()) + 1)
    return values, lines

def scan(local, upstream, abstract, window):
    index = defaultdict(list)
    corpus = []
    for number, record in enumerate(upstream):
        values, lines = tokenize(record, abstract)
        corpus.append((values, lines))
        for offset in range(len(values) - window + 1):
            key = tuple(values[offset:offset + window])
            index[key].append((number, offset))
    results = []
    for record in local:
        values, lines = tokenize(record, abstract)
        covered, candidates = {}, []
        for offset in range(len(values) - window + 1):
            key = tuple(values[offset:offset + window])
            # Repetitive sequences (arrays/boilerplate) are not useful evidence.
            if len(index.get(key, ())) > 1000:
                continue
            for number, other in index.get(key, ()):
                diagonal = (number, other - offset)
                if covered.get(diagonal, -1) >= offset + window:
                    continue
                reference, ref_lines = corpus[number]
                end, ref_end = offset + window, other + window
                while end < len(values) and ref_end < len(reference) and values[end] == reference[ref_end]:
                    end += 1
                    ref_end += 1
                covered[diagonal] = end
                candidates.append({'tokens': end - offset, 'local_lines': [lines[offset], lines[end - 1]],
                    'upstream_lines': [ref_lines[other], ref_lines[ref_end - 1]],
                    'upstream': {k: v for k, v in upstream[number].items() if k != 'text'}})
        # Deduplicate historical versions having the same candidate range.
        unique = {}
        for candidate in sorted(candidates, key=lambda x: -x['tokens']):
            key = (candidate['upstream']['family'], candidate['upstream']['path'], tuple(candidate['local_lines']))
            unique.setdefault(key, candidate)
        if unique:
            results.append({'local': {k: v for k, v in record.items() if k != 'text'},
                'candidates': list(unique.values())[:12]})
    return results

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', type=Path, required=True)
    parser.add_argument('--reader', type=Path, required=True)
    parser.add_argument('--sdk', type=Path, required=True)
    parser.add_argument('--converter', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    local = collect(args.project, 'EasyREAD', True)
    current = collect(args.project, 'EasyREAD', False)
    upstream = collect(args.reader, 'freeink-reader', True) + collect(args.sdk, 'FreeInk SDK', False) + collect(args.converter, 'epub-to-xtc-converter', False)
    report = {'schema': 1, 'limitations': 'Heuristic candidate search, not proof of copying or originality. Comments/preprocessor lines excluded; identifier abstraction preserves literals. Not a complete language parser. Top 12 deduplicated candidates per local blob/mode. Third-party dependencies and generated data require separate license review.',
        'revisions': {name: git(path, 'rev-parse', 'HEAD').decode().strip() for name, path in [('EasyREAD', args.project), ('freeink-reader', args.reader), ('FreeInk SDK', args.sdk), ('epub-to-xtc-converter', args.converter)]},
        'current_inventory': [{k: v for k, v in r.items() if k != 'text'} | {'lines': len(r['text'].splitlines())} for r in current],
        'historical_local_blobs': len(local), 'upstream_blobs': len(upstream)}
    report['thresholds'] = {'exact_tokens': 20, 'identifier_abstracted': 40, 'repetition_cutoff': 1000}
    for label, abstract, window in [('exact_tokens', False, 20), ('identifier_abstracted', True, 40)]:
        report[label] = scan(local, upstream, abstract, window)
        print(label, len(report[label]), 'local blobs with candidates', flush=True)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({k: report[k] for k in ['revisions', 'historical_local_blobs', 'upstream_blobs']}, indent=2))

if __name__ == '__main__':
    main()
